export const categories = ["All pieces", "Tableware", "Home accents", "Scent & ritual"];
export const freeShippingThreshold = 85;

export const formatCurrency = (amount) =>
  new Intl.NumberFormat("en-US", { style: "currency", currency: "USD" }).format(amount);

export const getCartSummary = (cart, couponCode = "") => {
  const itemCount = cart.reduce((total, item) => total + item.quantity, 0);
  const subtotal = cart.reduce((total, item) => total + item.price * item.quantity, 0);
  const discount = couponCode === "MORROW10" ? Math.round(subtotal * 0.1 * 100) / 100 : 0;
  const shipping = subtotal === 0 || subtotal - discount >= freeShippingThreshold ? 0 : 8;
  const estimatedTax = Math.round((subtotal - discount) * 0.08 * 100) / 100;

  return {
    itemCount,
    subtotal,
    discount,
    shipping,
    estimatedTax,
    total: subtotal - discount + shipping + estimatedTax,
    remainingForFreeShipping: Math.max(0, freeShippingThreshold - (subtotal - discount)),
  };
};
